import { isMap, isScalar, isSeq, type Document, type Scalar, YAMLMap } from 'yaml';
import {
	isObject,
	overrideString,
	parseYamlMap,
	splitKeyValue,
	type Json
} from '#lib/dockit-config.js';
import { PRESET_INFO, type Preset } from './presets';

/**
 * Backup hooks: commands that run before and after backups and restores, e.g.
 * a database dump. Restic only signals a phase, it doesn't know the commands
 * and needs no docker socket.
 *
 * A hook runner is a service of the project (same image as the service it
 * belongs to) that runs `.backup/agent.sh` and keeps its hooks in HOOK_*
 * variables. Dockit adds it to the compose override file. The project folder is the channel: restic writes the phase to
 * `.backup/requests/<runner>` for every runner registered in `.backup/agents`,
 * the runner deletes the request when it starts and answers in
 * `.backup/results/<runner>` (exit code, then the output).
 * Hooks write their output (dumps) to `.backup/dumps`, which is backed up with
 * the project.
 */
export const PHASES = [
	'pre-backup',
	'post-backup',
	'backup-failed',
	'pre-restore',
	'post-restore',
	'restore-failed'
] as const;
export type Phase = (typeof PHASES)[number];

export const hookVar = (phase: Phase) => `HOOK_${phase.toUpperCase().replace(/-/g, '_')}`;

/** folder of the hooks in a project */
export const HOOKS_DIR = '.backup';
/** where a runner sees the hooks folder */
const RUNNER_DIR = '/backup';
/** signalling, neither backed up nor restored */
const CONTROL_DIRS = ['agents', 'requests', 'results'].map((d) => `${HOOKS_DIR}/${d}`);
/** {@link CONTROL_DIRS} as excludes relative to the project folder */
export const CONTROL_EXCLUDES = CONTROL_DIRS.map((d) => `/${d}`);
/** where runners register: one file per runner that is up */
export const AGENTS_DIR = CONTROL_DIRS[0];
export const AGENT_FILE = 'agent.sh';
export const HOOKS_FILE = 'hooks.sh';
/** environment variable that marks a service as hook runner (and names it) */
const NAME_VAR = 'HOOKS_NAME';

/** The runner: written to `.backup/agent.sh` of every project with runners. */
export const AGENT_SCRIPT = `#!/bin/sh
# Backup hook runner, generated by Dockit's restic template (overwritten on changes).
# Runs the HOOK_* commands of this service when restic asks for them: restic
# writes the phase to requests/<runner>, the runner deletes the request, runs
# the hook and writes results/<runner> (exit code, then the output).
dir=/backup
name=\${HOOKS_NAME:?HOOKS_NAME is not set}
request=$dir/requests/$name
result=$dir/results/$name
mkdir -p "$dir/agents" "$dir/requests" "$dir/results" "$dir/dumps" || exit 1
# a request from before the start is stale: its backup or restore is gone
rm -f "$request"
: >"$dir/agents/$name"
trap 'rm -f "$dir/agents/$name"; exit 0' INT TERM
echo "Hook runner $name is ready"
while :; do
	# registered again if the registration was cleaned up
	[ -f "$dir/agents/$name" ] || : >"$dir/agents/$name"
	if [ -f "$request" ]; then
		phase=$(cat "$request")
		rm -f "$request"
		var=HOOK_$(echo "$phase" | tr 'a-z-' 'A-Z_')
		case "$phase" in
		${PHASES.join(' | ')})
			eval "command=\\\${$var:-}"
			;;
		*) command="echo 'Unknown phase $phase'; exit 1" ;;
		esac
		if [ -n "$command" ]; then
			echo "Running $var"
			out=$( (cd "$dir" && sh -ec "$command") 2>&1)
			code=$?
			[ -z "$out" ] || echo "$out"
		else
			out="No $var hook"
			code=0
		fi
		printf '%s\\n%s\\n' "$code" "$out" >"$result.tmp" && mv "$result.tmp" "$result"
		echo "$var finished with exit code $code"
	fi
	sleep 1 &
	wait $!
done
`;

/** The restic side: `conf/hooks.sh` of the restic project, called by resticprofile and Dockit. */
export const HOOKS_SCRIPT = `#!/bin/sh
# Backup hooks, generated by Dockit's restic template (overwritten on changes).
# Usage: hooks.sh <phase> <project folder>
# Asks every hook runner registered in <project>/${HOOKS_DIR}/agents to run its
# hooks of the phase and waits for the answers. Fails when a hook fails or a
# runner doesn't answer.
phase=$1
dir=$2/${HOOKS_DIR}
ack=\${HOOKS_ACK_TIMEOUT:-30}
timeout=\${HOOKS_TIMEOUT:-3600}
runners=$(ls "$dir/agents" 2>/dev/null)
[ -n "$runners" ] || exit 0
cleanup() {
	for r in $runners; do rm -f "$dir/requests/$r" "$dir/results/$r"; done
}
trap cleanup EXIT
trap 'exit 1' INT TERM
mkdir -p "$dir/requests" "$dir/results" || exit 1
# left over by a killed run
cleanup
for r in $runners; do
	echo "$phase" >"$dir/requests/.$r" && mv "$dir/requests/.$r" "$dir/requests/$r" || exit 1
done
echo "Running the $phase hooks of $(echo $runners)"
status=0
pending=$runners
elapsed=0
while [ -n "$pending" ]; do
	left=
	for r in $pending; do
		result="$dir/results/$r"
		if [ -f "$result" ]; then
			code=$(head -n 1 "$result")
			echo "--- $phase hooks of $r: exit code $code"
			tail -n +2 "$result"
			[ "$code" = 0 ] || status=1
		elif [ -f "$dir/requests/$r" ] && [ "$elapsed" -ge "$ack" ]; then
			echo "--- $r did not answer within \${ack}s. Is it running?"
			status=1
		elif [ "$elapsed" -ge "$timeout" ]; then
			echo "--- $phase hooks of $r did not finish within \${timeout}s"
			status=1
		else
			left="$left $r"
		fi
	done
	pending=$left
	[ -n "$pending" ] || break
	sleep 1
	elapsed=$((elapsed + 1))
done
exit $status
`;

/** `environment` of a compose service as a map (it can be a list of `KEY=value`). */
function environment(service: Json): Record<string, string | null> {
	const env = service.environment;
	if (Array.isArray(env)) {
		return Object.fromEntries(
			env.filter((e): e is string => typeof e === 'string').map(splitKeyValue)
		);
	}
	if (env && typeof env === 'object') {
		return Object.fromEntries(
			Object.entries(env).map(([k, v]) => [k, v === null || v === undefined ? null : String(v)])
		);
	}
	return {};
}

export interface Runner {
	/** compose service */
	service: string;
	/** name it registers with (HOOKS_NAME) */
	name: string;
	/** the service whose volumes it uses */
	target: string | null;
	/** phases with a hook */
	phases: Phase[];
}

const services = (json: Json) =>
	(isObject(json.services) ? json.services : {}) as Record<string, Json | null>;

/** The hook runners of a parsed compose file. */
export function readRunners(json: Json): Runner[] {
	return Object.entries(services(json)).flatMap(([service, s]) => {
		if (!s) return [];
		const env = environment(s);
		const name = env[NAME_VAR]?.trim();
		if (!name) return [];
		const from = Array.isArray(s.volumes_from) ? s.volumes_from[0] : undefined;
		return [
			{
				service,
				name,
				target:
					typeof from === 'string' ? from.replace(/^service:/, '').replace(/:(ro|rw)$/, '') : null,
				phases: PHASES.filter((p) => !!env[hookVar(p)]?.trim())
			}
		];
	});
}

/** Waits up to 2 minutes until the database answers (it may initialize first). */
const waitFor = (check: string) => `timeout 120 sh -c 'until ${check}; do sleep 1; done'`;

/**
 * Environment and hooks of a preset. Compose interpolates `$`, so the shell's
 * variables are written as `$$`. Hooks run with `sh -e` in /backup.
 */
function presetHooks(preset: Preset, host: string): Record<string, string> {
	switch (preset) {
		case 'postgres': {
			const file = `dumps/${host}.dump`;
			const login = 'export PGUSER="$${POSTGRES_USER:-postgres}" PGPASSWORD="$$POSTGRES_PASSWORD"';
			const db = '"$${POSTGRES_DB:-$$PGUSER}"';
			return {
				PGHOST: host,
				[hookVar('pre-backup')]: [
					login,
					`pg_dump -Fc -f ${file}.tmp ${db}`,
					`mv ${file}.tmp ${file}`
				].join('\n'),
				[hookVar('post-restore')]: [
					login,
					`[ -f ${file} ] || { echo "No dump to restore"; exit 0; }`,
					waitFor('pg_isready -q'),
					`pg_restore --clean --if-exists --single-transaction -d ${db} ${file}`
				].join('\n')
			};
		}
		case 'mysql':
		case 'mariadb': {
			const file = `dumps/${host}.sql`;
			const [dump, admin, client, password] =
				preset === 'mysql'
					? ['mysqldump', 'mysqladmin', 'mysql', '$$MYSQL_ROOT_PASSWORD']
					: [
							'mariadb-dump',
							'mariadb-admin',
							'mariadb',
							'$${MARIADB_ROOT_PASSWORD:-$$MYSQL_ROOT_PASSWORD}'
						];
			const login = `export MYSQL_PWD="${password}"`;
			return {
				MYSQL_HOST: host,
				[hookVar('pre-backup')]: [
					login,
					`${dump} -uroot --single-transaction --routines --events --all-databases >${file}.tmp`,
					`mv ${file}.tmp ${file}`
				].join('\n'),
				[hookVar('post-restore')]: [
					login,
					`[ -f ${file} ] || { echo "No dump to restore"; exit 0; }`,
					waitFor(`${admin} -uroot ping --silent`),
					`${client} -uroot <${file}`
				].join('\n')
			};
		}
		case 'mongo': {
			const file = `dumps/${host}.archive`;
			const login =
				'[ -z "$$MONGO_INITDB_ROOT_USERNAME" ] || set -- --username "$$MONGO_INITDB_ROOT_USERNAME" --password "$$MONGO_INITDB_ROOT_PASSWORD" --authenticationDatabase admin';
			return {
				[hookVar('pre-backup')]: [
					login,
					`mongodump --host ${host} "$$@" --archive=${file}.tmp`,
					`mv ${file}.tmp ${file}`
				].join('\n'),
				[hookVar('post-restore')]: [
					login,
					`[ -f ${file} ] || { echo "No dump to restore"; exit 0; }`,
					waitFor(`mongosh --host ${host} --quiet --eval 1 >/dev/null 2>&1`),
					`mongorestore --host ${host} "$$@" --drop --archive=${file}`
				].join('\n')
			};
		}
		case 'redis':
		case 'valkey': {
			// SAVE writes the snapshot synchronously: the volume is consistent for the backup
			return {
				[hookVar('pre-backup')]: [
					'[ -z "$$REDIS_PASSWORD" ] || export REDISCLI_AUTH="$$REDIS_PASSWORD"',
					`out=$$(${preset}-cli -h ${host} SAVE)`,
					'echo "$$out"',
					'[ "$$out" = OK ]'
				].join('\n')
			};
		}
		case 'influxdb': {
			const dir = `dumps/${host}.influx`;
			const login = 'export INFLUX_TOKEN="$${INFLUX_TOKEN:-$$DOCKER_INFLUXDB_INIT_ADMIN_TOKEN}"';
			const token =
				'[ -n "$$INFLUX_TOKEN" ] || { echo "Set INFLUX_TOKEN to an operator token"; exit 1; }';
			return {
				INFLUX_HOST: `http://${host}:8086`,
				[hookVar('pre-backup')]: [
					login,
					token,
					`rm -rf ${dir}.tmp`,
					`influx backup ${dir}.tmp`,
					`rm -rf ${dir}`,
					`mv ${dir}.tmp ${dir}`
				].join('\n'),
				[hookVar('post-restore')]: [
					login,
					`[ -d ${dir} ] || { echo "No backup to restore"; exit 0; }`,
					token,
					waitFor('influx ping >/dev/null 2>&1'),
					`influx restore --full ${dir}`
				].join('\n')
			};
		}
		case 'custom':
			return {};
	}
}

function runnerComment(target: string) {
	return [
		` Backup hooks of ${target}: runs its HOOK_* commands when restic asks for them,`,
		` ${PHASES.slice(0, 3).map(hookVar).join(', ')},`,
		` ${PHASES.slice(3).map(hookVar).join(', ')}.`,
		` They run with sh -e in ${RUNNER_DIR} (= ./${HOOKS_DIR}), dumps go to ${RUNNER_DIR}/dumps.`,
		' Write $$ for a $ of the shell.'
	].join('\n');
}

/** Docker names of the named volumes of a service (external ones are not ours). */
function serviceVolumes(json: Json, service: Json, composeName: string) {
	const top = (json.volumes && typeof json.volumes === 'object' ? json.volumes : {}) as Record<
		string,
		Json | null
	>;
	const mounts = Array.isArray(service.volumes) ? service.volumes : [];
	return mounts.flatMap((m) => {
		const source =
			typeof m === 'string'
				? m.split(':')[0]
				: m && typeof m === 'object' && (m as Json).type === 'volume'
					? (m as Json).source
					: undefined;
		if (typeof source !== 'string' || !(source in top)) return [];
		const def = top[source] ?? {};
		if (def.external) return [];
		return [typeof def.name === 'string' ? def.name : `${composeName}_${source}`];
	});
}

function getServices(doc: Document) {
	let s = doc.get('services', true);
	if (s === undefined || s === null) {
		s = new YAMLMap();
		doc.set('services', s);
	}
	if (!isMap(s)) throw new Error('The compose file has no services');
	return s;
}

/**
 * Adds a hook runner for a service of the (merged) compose file to the
 * override file, right after the service if the override has it. Returns the
 * new override file and, for presets that dump the database, the volumes of
 * the service: their raw files are not needed in the backup anymore.
 */
export function addRunner(
	compose: Json,
	override: string,
	service: string,
	composeName: string,
	preset: Preset = 'custom'
) {
	const doc = parseYamlMap(override);
	const all = services(compose);
	const target = all[service];
	if (!target) throw new Error(`There is no service ${service}`);
	if (environment(target)[NAME_VAR]) throw new Error(`${service} is a hook runner itself`);
	if (typeof target.image !== 'string') {
		throw new Error(`${service} has no image: the runner needs the image of the service`);
	}
	if (readRunners(compose).some((r) => r.target === service)) {
		throw new Error(`${service} already has a hook runner`);
	}
	let name = `${service}-hooks`;
	for (let i = 2; name in all; i++) name = `${service}-hooks-${i}`;

	const runner: Json = { image: target.image, restart: 'unless-stopped', depends_on: [service] };
	for (const key of ['profiles', 'env_file', 'network_mode']) {
		if (target[key] !== undefined) runner[key] = target[key];
	}
	// same networks, without aliases or static addresses
	if (target.networks && !target.network_mode) {
		runner.networks = Array.isArray(target.networks)
			? target.networks
			: Object.keys(target.networks as Json);
	}
	runner.volumes_from = [service];
	runner.volumes = [`./${HOOKS_DIR}:${RUNNER_DIR}`];
	runner.entrypoint = ['sh', `${RUNNER_DIR}/${AGENT_FILE}`];
	runner.environment = {
		...environment(target),
		[NAME_VAR]: name,
		...presetHooks(preset, service)
	};

	const map = getServices(doc);
	const node = doc.createNode(runner) as YAMLMap;
	const entrypoint = node.get('entrypoint', true);
	if (isSeq(entrypoint)) entrypoint.flow = true;
	// readable multi-line commands
	const env = node.get('environment', true);
	for (const pair of isMap(env) ? env.items : []) {
		const value = pair.value;
		if (isScalar(value) && typeof value.value === 'string' && value.value.includes('\n')) {
			value.type = 'BLOCK_LITERAL';
		}
	}
	const key = doc.createNode(name) as Scalar;
	key.commentBefore = runnerComment(service);
	const index = map.items.findIndex((p) => (p.key as Scalar)?.value === service);
	const at = index === -1 ? map.items.length : index + 1;
	map.items.splice(at, 0, doc.createPair(key, node));
	// a blank line between the services, like the rest of the file
	if (at > 0) key.spaceBefore = true;
	return {
		override: doc.toString(),
		volumes: PRESET_INFO[preset].keepsVolumes ? [] : serviceVolumes(compose, target, composeName)
	};
}

/**
 * Removes a hook runner from the file that defines it: the override file, or
 * the compose file for runners added before the override file was used.
 */
export function removeRunner(compose: string, override: string, service: string) {
	/** The services of `source` without the runner, `null` = it isn't defined there. */
	const without = (source: string) => {
		const doc = parseYamlMap(source);
		if (!readRunners(doc.toJS() as Json).some((r) => r.service === service)) return null;
		const map = getServices(doc);
		map.delete(service);
		return { doc, map };
	};
	const fromOverride = override ? without(override) : null;
	if (fromOverride) {
		if (fromOverride.map.items.length === 0) fromOverride.doc.delete('services');
		return { compose, override: overrideString(fromOverride.doc) };
	}
	const fromCompose = without(compose);
	if (fromCompose) return { compose: fromCompose.doc.toString(), override };
	throw new Error(`${service} is not a hook runner`);
}

/** Services a runner can be added for: with an image, not a runner and without one. */
export function runnerCandidates(json: Json, runners = readRunners(json)) {
	return Object.entries(services(json)).flatMap(([name, s]) => {
		if (!s || typeof s.image !== 'string' || environment(s)[NAME_VAR]) return [];
		if (runners.some((r) => r.target === name)) return [];
		return [{ name, image: s.image }];
	});
}
